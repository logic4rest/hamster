"""
할아버지의 낡은 시계 (My Grandfather's Clock) 연주 및 LED 시계 애니메이션 스크립트
================================================================================
실행 방법:
    python tools/play_grandfathers_clock.py
    또는
    uv run python tools/play_grandfathers_clock.py
"""

import time
import sys
from roboid import Hamster, wait

def play_grandfathers_clock():
    print("햄스터 로봇에 연결하는 중...")
    try:
        hamster = Hamster()
        wait(1000)  # 연결 대기
        print("연결 성공!")
    except Exception as e:
        print(f"햄스터 연결 실패: {e}")
        print("BLE 동글과 햄스터 전원을 확인하세요.")
        return

    print("\n" + "=" * 60)
    print("   🕰️ 할아버지의 낡은 시계 (Grandfather's Clock) 연주 시작 🕰️")
    print("=" * 60)
    
    # 템포 설정 (BPM: 110 - 차분한 시계 속도)
    hamster.tempo(110)

    # 멜로디 정의 (음정, 박자)
    melody = [
        # [1절 도입부] 할아버지의 낡은 시계는 할아버지의 방에서
        ("G4", 0.5),
        ("C5", 0.5), ("B4", 0.5), ("C5", 0.5), ("D5", 0.5),
        ("C5", 0.5), ("D5", 0.5), ("E5", 1.0),
        ("F5", 0.5), ("E5", 0.5), ("A4", 0.5), ("D5", 0.5),
        ("D5", 1.0),
        ("C5", 0.5), ("C5", 0.5), ("C5", 0.5), ("B4", 0.5),
        ("A4", 0.5), ("B4", 0.5), ("C5", 1.5),

        # [1절 후반부] 백구십년 동안 쉬지 않고 똑딱똑딱 할아버지와 함께
        ("G4", 0.25), ("G4", 0.25),
        ("C5", 0.5), ("B4", 0.5), ("C5", 0.5), ("D5", 0.5),
        ("C5", 0.5), ("D5", 0.5), ("E5", 0.5), ("F5", 0.5),
        ("E5", 0.5), ("A4", 0.5), ("D5", 0.5), ("D5", 1.0),
        ("C5", 0.5), ("C5", 0.5), ("C5", 0.5), ("B4", 0.5),
        ("A4", 0.5), ("B4", 0.5), ("C5", 1.5),

        # [브릿지] 태어날 때 아침에 종소리 울리던 기쁠 때나 슬플 때나
        ("C5", 0.5), ("E5", 0.5), ("G5", 0.5), ("E5", 0.5),
        ("D5", 0.5), ("C5", 0.5), ("B4", 0.5), ("C5", 0.5),
        ("D5", 0.5), ("C5", 0.5), ("B4", 0.5), ("A4", 0.5),
        ("G4", 1.5),
        ("C5", 0.5), ("E5", 0.5), ("G5", 0.5), ("E5", 0.5),
        ("D5", 0.5), ("C5", 0.5), ("B4", 0.5), ("C5", 0.5),
        ("D5", 1.5),

        # [브릿지 후반] 할아버지 돌아가신 그 날 아침에
        ("G4", 0.25), ("G4", 0.25),
        ("C5", 0.5), ("D5", 0.5),
        ("E5", 0.5), ("E5", 0.5), ("F5", 0.5), ("E5", 0.5),
        ("A4", 0.5), ("D5", 0.5), ("D5", 1.0),
        ("C5", 0.5), ("B4", 0.5), ("C5", 1.5),

        # [후렴 - 똑딱똑딱 시계 파트] 종소리 똑딱똑딱 할아버지의 시계
        ("G4", 0.25), ("G4", 0.25),
        ("C5", 0.5),
        ("G4", 0.25), ("G4", 0.25), ("A4", 0.25), ("A4", 0.25),
        ("G4", 1.0),
        ("E4", 0.5), ("G4", 0.5), ("E4", 0.5), ("G4", 0.5),
        ("C4", 1.0),
        ("G4", 0.25), ("G4", 0.25), ("A4", 0.25), ("A4", 0.25),
        ("G4", 1.0),
        ("E4", 0.5), ("G4", 0.5), ("E4", 0.5), ("G4", 0.5),
        ("G4", 0.5),
        ("C5", 0.5), ("D5", 0.5),

        # [엔딩] 이제는 더 가지 않네
        ("E5", 0.25), ("E5", 0.25), ("F5", 0.5), ("E5", 0.5),
        ("A4", 0.5),
        ("D5", 0.25), ("D5", 0.25), ("C5", 0.5), ("B4", 0.5),
        ("C5", 1.5)
    ]

    tick = True
    for i, (note_name, beats) in enumerate(melody):
        # 틱톡 LED 애니메이션 (시계추 흔들림 구현)
        if tick:
            hamster.leds("red", "off")   # 왼쪽 빨강
            sys.stdout.write("\r🕰️  똑 틱 [◀]  |  음정: {:3s}".format(note_name))
        else:
            hamster.leds("off", "blue")  # 오른쪽 파랑
            sys.stdout.write("\r🕰️  틱 똑 [▶]  |  음정: {:3s}".format(note_name))
        sys.stdout.flush()
        tick = not tick

        # 음 연주
        hamster.note(note_name, beats)

    # 연주 종료
    hamster.note("off")
    hamster.leds("green", "green")  # 완료 표시 초록 LED
    print("\n\n🎉 연주가 완료되었습니다!")
    wait(1000)
    hamster.leds("off", "off")

if __name__ == "__main__":
    play_grandfathers_clock()
